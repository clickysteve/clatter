#!/usr/bin/env python3
"""Generate lxr/bridge/lxr_params.c from the firmware's MidiParser.c.

CLATTER needs the LXR's parameter handler (midiParser_ccHandler): the function that turns a
0-127 sound parameter value into the DSP state of a voice, exactly as the hardware does when
a knob turns, a kit loads, an LFO or velocity modulates a parameter or a step automates one.
The rest of MidiParser.c (the MIDI byte parser, MTC, routing, note handling) belongs to the
hardware's MIDI ports and the LXR sequencer, which CLATTER replaces.

This script copies the handler verbatim from the upstream file and makes only the changes
listed in EDITS (each one documented in docs/LXR_PORT.md):

  1. includes of hardware modules (UART, USB, sequencer clock sync, CortexParser) removed;
  2. the CC2_MUTE_x cases (they mute the LXR sequencer's tracks) do nothing;
  3. the CC2_FX_TYPE case no longer switches the LCD menu page.

Run from the repository root:  python3 lxr/tools/extract-params.py
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[1]
src = (root / 'upstream/Core/Src/Soundengine/MIDI/MidiParser.c').read_text()
lines = src.split('\n')
# everything up to the MTC checker (the handler and the helpers it uses)
end = next(i for i, l in enumerate(lines) if l.startswith('void midiParser_checkMtc'))
# back up over the comment block before it
while end > 0 and lines[end - 1].startswith('//'):
    end -= 1
body = '\n'.join(lines[:end])

EDITS = [
    ('#include <Soundengine/MIDI/CortexParser.h>\n', ''),
    ('#include "Soundengine/MIDI/Uart.h"\n', ''),
    ('#include "Soundengine/Sequencer/clockSync.h"\n', ''),
    ('#include "Soundengine/USB/usb_manager.h"\n', ''),
    ('''				if(value.itg == 0)
				{
					seq_setMute(voiceNr,0);
				}
				else
				{
					seq_setMute(voiceNr,1);
				}
''', '''				(void)voiceNr; /* CLATTER: track mutes belong to CLATTER's sequencer */
'''),
    ('''				//change visible parameters to selected FX type
				if(menu_activePage == FX_MODE_PAGE)
				{
					if(menu_getSubPage() != fxBus.fxType)
						menu_switchSubPage(fxBus.fxType, 1 );
				}
''', '''				/* CLATTER: no LCD menu page to switch */
'''),
]
for old, new in EDITS:
    if body.count(old) != 1:
        sys.exit(f'extract-params: expected exactly one occurrence of:\n{old}')
    body = body.replace(old, new)

header = '''/*
 * lxr_params.c - GENERATED by lxr/tools/extract-params.py. Do not edit by hand.
 *
 * The LXR-02 firmware's sound parameter handler, extracted from
 * Core/Src/Soundengine/MIDI/MidiParser.c (upstream revision in lxr/upstream/UPSTREAM_REVISION)
 * and MODIFIED for CLATTER: hardware includes removed, the sequencer mute and LCD menu calls
 * removed (see the script and docs/LXR_PORT.md). The copyright notice below is the upstream
 * file's own.
 */
'''
(root / 'bridge/lxr_params.c').write_text(header + body + '\n')
print('wrote lxr/bridge/lxr_params.c', len(body.split(chr(10))), 'lines')
