#!/usr/bin/env node
/**
 * Turns two kit-evaluation reports (eval/kits.eval.ts) into a before/after markdown table.
 *
 *   node scripts/eval-report.mjs docs/eval/baseline.json docs/eval/after.json > docs/eval/REPORT.md
 */
import { readFileSync } from 'node:fs';

const [beforePath, afterPath] = process.argv.slice(2);
if (!beforePath || !afterPath) {
  console.error('usage: eval-report.mjs before.json after.json');
  process.exit(1);
}
const b = JSON.parse(readFileSync(beforePath, 'utf8'));
const a = JSON.parse(readFileSync(afterPath, 'utf8'));

const INSTR = ['kick', 'ltom', 'htom', 'snare', 'clap', 'chat', 'ohat', 'cymbal', 'perc', 'fx'];
const WILD = Object.keys(a.byWildness);
const f = (x, d = 1) => (typeof x === 'number' ? (Number.isInteger(x) ? String(x) : x.toFixed(d)) : '-');
const row = (...cells) => `| ${cells.join(' | ')} |`;
const table = (head, rows) => [row(...head), row(...head.map((_, i) => (i === 0 ? '---' : '---:'))), ...rows.map((r) => row(...r))].join('\n');
const delta = (x, y, d = 1, unit = '') => `${f(x, d)}${unit} → ${f(y, d)}${unit}`;

const out = [];
out.push(`# Kit generation: before and after`);
out.push('');
out.push(`Generated by \`scripts/eval-report.mjs\` from \`${beforePath}\` (${b.label}) and \`${afterPath}\` (${a.label}).`);
out.push(`Each run renders ${a.kits} kits with the real LXR engine (6 CHARACTERs × 4 WILDNESS levels × ${a.kits / 24} seeds; two thirds with a kick/toms/snare layout, one third with a perc/fx/clap layout), ${a.sounds} individual sounds.`);
out.push('');
out.push('## Safety (every sound of every kit)');
out.push('');
out.push(
  table(
    ['', 'before', 'after'],
    INSTR.map((i) => [i, `${f(b.overall[i]?.unsafePct, 2)} % unsafe, ${f(b.overall[i]?.silentPct, 2)} % silent, ${f(b.overall[i]?.clipPct, 2)} % clipped`, `${f(a.overall[i]?.unsafePct, 2)} % unsafe, ${f(a.overall[i]?.silentPct, 2)} % silent, ${f(a.overall[i]?.clipPct, 2)} % clipped`]),
  ),
);
out.push('');
out.push('## Does it sound like its instrument? (share of sounds that fit the strict reading of the instrument)');
out.push('');
out.push('Before the change WILDNESS did nothing for GENERATE KIT, so the four columns are the same population. After it, low WILDNESS should be recognisable and high WILDNESS should be free to be strange.');
out.push('');
out.push(table(['', 'all before', ...WILD.map((w) => `after w=${w}`), 'all after'], INSTR.map((i) => [i, f(b.overall[i]?.looksLikePct, 0) + ' %', ...WILD.map((w) => f(a.byWildness[w].instruments[i]?.looksLikePct, 0) + ' %'), f(a.overall[i]?.looksLikePct, 0) + ' %'])));
out.push('');
out.push('## Measured character of the sounds (medians)');
out.push('');
out.push(
  table(
    ['', 'length ms', 'centroid Hz', 'low-frequency share', 'noise', 'transient dB'],
    INSTR.map((i) => {
      const x = b.overall[i];
      const y = a.overall[i];
      return [i, delta(x?.lengthMs.p50, y?.lengthMs.p50, 0), delta(x?.centroidHz.p50, y?.centroidHz.p50, 0), delta(x?.low, y?.low, 2), delta(x?.noise, y?.noise, 2), delta(x?.transientDb, y?.transientDb, 1)];
    }),
  ),
);
out.push('');
out.push('## Kit as a whole');
out.push('');
const kb = b.kit;
const ka = a.kit;
out.push(
  table(
    ['measure', 'before', 'after'],
    [
      ['spread of decay lengths (octaves, std dev)', f(kb.decaySpreadOct, 2), f(ka.decaySpreadOct, 2)],
      ['spectral range of the voices (octaves of centroid)', f(kb.centroidRangeOct, 2), f(ka.centroidRangeOct, 2)],
      ['level range between voices (dB)', f(kb.levelRangeDb, 1), f(ka.levelRangeDb, 1)],
      ['kits with a voice over 0.9 peak', f(kb.loudKitsPct, 1) + ' %', f(ka.loudKitsPct, 1) + ' %'],
      ['kits whose voices all share one decay (spread < 0.6 oct)', f(kb.sameDecayKitsPct, 1) + ' %', f(ka.sameDecayKitsPct, 1) + ' %'],
      ['kits whose toms are too alike', f(kb.tomsTooAlikePct, 1) + ' %', f(ka.tomsTooAlikePct, 1) + ' %'],
      ['kits whose closed and open hat are too alike', f(kb.hatsTooAlikePct, 1) + ' %', f(ka.hatsTooAlikePct, 1) + ' %'],
      ['sameness (sum of pair similarities, lower is more varied)', f(kb.sameness, 2), f(ka.sameness, 2)],
      ['how differently bright the voices are (std dev of high-frequency share)', f(kb.brightSpread, 3), f(ka.brightSpread, 3)],
    ],
  ),
);
out.push('');
out.push('## CHARACTER and WILDNESS');
out.push('');
out.push(
  table(
    ['measure', 'before', 'after'],
    [
      ['CHARACTER separation (mean distance between the six CHARACTERs, standardised features)', f(b.characterSeparation, 2), f(a.characterSeparation, 2)],
      ['WILDNESS separation (distance between the four levels)', f(b.wildnessSeparation, 2), f(a.wildnessSeparation, 2)],
      ...WILD.map((w) => [`nearest-neighbour distance at w=${w} (higher: sounds repeat themselves less)`, f(b.byWildness[w]?.nearestNeighbour, 2), f(a.byWildness[w].nearestNeighbour, 2)]),
    ],
  ),
);
out.push('');
out.push('Spread of kick decay and spectral centroid (octaves) by WILDNESS, after:');
out.push('');
out.push(table(['wildness', 'kick decay spread', 'kick centroid spread', 'snare decay spread', 'cymbal decay spread'], WILD.map((w) => [w, f(a.byWildness[w].instruments.kick?.lengthOctSd, 2), f(a.byWildness[w].instruments.kick?.centroidOctSd, 2), f(a.byWildness[w].instruments.snare?.lengthOctSd, 2), f(a.byWildness[w].instruments.cymbal?.lengthOctSd, 2)])));
out.push('');
out.push('## MUTATE (kit mutated at 40 %, then checked)');
out.push('');
if (a.mutation?.chosen && b.mutation?.plain) {
  const mp = b.mutation.plain;
  const mc = a.mutation.chosen;
  out.push(
    table(
      ['measure', 'before (plain mutation)', 'after (chosen among candidates)'],
      [
        ['sounds', mp.sounds, mc.sounds],
        ['unsafe', f(mp.unsafePct, 2) + ' %', f(mc.unsafePct, 2) + ' %'],
        ['sound like their instrument (all WILDNESS)', f(mp.looksLikePct, 1) + ' %', f(mc.looksLikePct, 1) + ' %'],
        ['sound like their instrument (WILDNESS 0.1 and 0.4)', f(mp.lowWildLooksLikePct, 1) + ' %', f(mc.lowWildLooksLikePct, 1) + ' %'],
        ['how far the sound moved (octaves of centroid + length)', f(mp.movedOctaves, 2), f(mc.movedOctaves, 2)],
        ['time to check one mutated kit', f(mp.msPerKit, 0) + ' ms', f(mc.msPerKit, 0) + ' ms'],
      ],
    ),
  );
}
out.push('');
out.push('## Pitch of kick and toms (YIN, a quarter of the kits)');
out.push('');
out.push(table(['', 'stable before → after', 'stability before → after', 'sweep (cents) before → after'], ['kick', 'ltom', 'htom'].map((i) => {
  const x = b.pitch[i];
  const y = a.pitch[i];
  return [i, `${f((100 * (x.kinds.stable ?? 0)) / x.n, 0)} % → ${f((100 * (y.kinds.stable ?? 0)) / y.n, 0)} %`, delta(x.stability, y.stability, 2), delta(x.sweepCents, y.sweepCents, 0)];
})));
out.push('');
out.push('## Cost');
out.push('');
out.push(table(['', 'before', 'after'], [['engine check of a whole kit (GENERATE KIT, in the worker)', f(kb.msPerKit, 0) + ' ms', f(ka.msPerKit, 0) + ' ms']]));
out.push('');
console.log(out.join('\n'));
