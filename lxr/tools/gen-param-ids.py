#!/usr/bin/env python3
"""Generate src/sound/lxrParamIds.ts from the firmware's Parameters.h (enum ParamEnums).

The TypeScript side addresses LXR sound parameters by the firmware's own numbers, so this
table must match the compiled engine exactly. Run from the repository root:
    python3 lxr/tools/gen-param-ids.py
"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / 'lxr/upstream/Core/Inc/Parameters.h').read_text()
body = src[src.index('enum ParamEnums'):]
body = body[body.index('{') + 1: body.index('};')]
body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
body = re.sub(r'//[^\n]*', '', body)
names = {}
value = -1
for item in body.split(','):
    item = item.strip()
    if not item:
        continue
    if '=' in item:
        name, expr = [x.strip() for x in item.split('=')]
        value = names[expr] if expr in names else int(expr, 0)
    else:
        name = item
        value += 1
    names[name] = value
out = ['/**',
       ' * GENERATED by lxr/tools/gen-param-ids.py from the LXR firmware\'s Parameters.h',
       ' * (enum ParamEnums). Do not edit by hand.',
       ' *',
       ' * Copyright (C) 2012-2026 Erica Synths; generated table (C) 2026 The CLATTER contributors.',
       ' * SPDX-License-Identifier: GPL-3.0-only',
       ' */',
       'export const PAR = {']
for n, v in names.items():
    out.append(f'  {n[4:] if n.startswith("PAR_") else n}: {v},')
out.append('} as const;')
out.append('export type ParId = (typeof PAR)[keyof typeof PAR];')
out.append(f'/** Number of sound parameters (END_OF_SOUND_PARAMETERS). */')
out.append(f'export const SOUND_PARAM_COUNT = {names["END_OF_SOUND_PARAMETERS"]};')
dst = root / 'src/sound/lxrParamIds.ts'
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text('\n'.join(out) + '\n')
print('wrote', dst, len(names), 'names; END_OF_SOUND_PARAMETERS =', names['END_OF_SOUND_PARAMETERS'])
